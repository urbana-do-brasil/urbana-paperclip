const messages: Record<SupportedLocale, Record<keyof typeof en, string>> = { en, "pt-BR": ptBR };

export type SetupMessageKey = keyof typeof en;

/** Localized wording shared by the setup commands and their help text. */
export function setupMessage(key: SetupMessageKey, values: Record<string, string | number | boolean> = {}, locale?: SupportedLocale): string {
  const message = messages[locale ?? getCliLocale()][key];
  return message.replace(/\{(\w+)\}/g, (placeholder, name: string) => String(values[name] ?? placeholder));
}

const commandHelp: Record<string, { description: SetupMessageKey; options: Record<string, SetupMessageKey> }> = {
  onboard: {
    description: "onboardDescription",
    options: {
      "--config": "configOption",
      "--data-dir": "dataDirOption",
      "--bind": "onboardBindOption",
      "--yes": "onboardYesOption",
      "--install-service": "installServiceOption",
      "--no-install-service": "noInstallServiceOption",
      "--run": "runOption",
    },
  },
  configure: {
    description: "configureDescription",
    options: { "--config": "configOption", "--data-dir": "dataDirOption", "--section": "configureSectionOption" },
  },
  env: {
    description: "envDescription",
    options: { "--config": "configOption", "--data-dir": "dataDirOption" },
  },
};

/** Translate descriptions while keeping command and option names unchanged. */
export function applySetupHelpLocalization(root: Command, locale: SupportedLocale): void {
  for (const command of root.commands) {
    const help = commandHelp[command.name()];
    if (!help) continue;
    command.description(setupMessage(help.description, {}, locale));
    for (const option of command.options) {
      const key = option.long ? help.options[option.long] : undefined;
      if (key) option.description = setupMessage(key, {}, locale);
    }
  }
}
